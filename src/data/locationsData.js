/**
 * Returns list of supported States (currently Gujarat)
 */
export const getStates = () => Object.keys(LOCATIONS_DATA);

/**
 * Returns districts for a given state
 */
export const getDistricts = (stateName) => {
  if (!stateName || !LOCATIONS_DATA[stateName]) return [];
  return Object.keys(LOCATIONS_DATA[stateName].districts);
};

/**
 * Returns cities/talukas for a given state and district
 */
export const getCities = (stateName, districtName) => {
  if (!stateName || !districtName) return [];
  const districtObj = LOCATIONS_DATA[stateName]?.districts?.[districtName];
  if (!districtObj) return [];
  return Object.keys(districtObj.cities);
};

/**
 * Returns villages for a given state, district, and city/taluka
 */
export const getVillages = (stateName, districtName, cityName) => {
  if (!stateName || !districtName || !cityName) return [];
  const villagesList = LOCATIONS_DATA[stateName]?.districts?.[districtName]?.cities?.[cityName];
  return Array.isArray(villagesList) ? villagesList : [];
};

export default LOCATIONS_DATA;
